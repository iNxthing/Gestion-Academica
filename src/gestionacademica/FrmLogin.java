    public void login(){
        try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
                String consulta = "call sp_login(?, ?)";
    
                try (PreparedStatement ps = conexion.prepareStatement(consulta)) {
                    ps.setString(1, txtUser.getText().trim());
                    ps.setString(2, String.valueOf(txtPass.getPassword()));
    
                    try (ResultSet rs = ps.executeQuery()) {
                        if (rs.next()) {
                            int idUsuario = rs.getInt("idUsuario");
                            int cargo = rs.getInt("idPerfil");
                            int idProfesor = rs.getInt("idProfesor");
    
                            if (idUsuario != 0) {
                                FrmPrincipal principal = new FrmPrincipal(idUsuario, cargo, idProfesor);
                                principal.setVisible(true);
                                this.dispose();
                            } else {
                                JOptionPane.showMessageDialog(null, "Error de usuario y/o contraseña", "Gestión Académica", JOptionPane.ERROR_MESSAGE);
                            }
                        }
                    }
                }
            
        }catch (SQLException e) {
            JOptionPane.showMessageDialog(this,"Error de la base de datos " + e);
        }
    }
