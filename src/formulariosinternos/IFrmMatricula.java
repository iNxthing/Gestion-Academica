    private void btnMatricularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMatricularActionPerformed
        // TODO add your handling code here:
        String documento = txtDocumento.getText().trim();
        String nombre = txtNombreCompleto.getText().trim();
        int gradoSeleccionado = cbmGrado.getSelectedIndex() - 1;
        if(documento.isEmpty() || nombre.isEmpty() || gradoSeleccionado == 0){
            JOptionPane.showMessageDialog(this, "Debes llenar todos los campos para poder matricular un estudiante");
            return;
        }
        
        Grado grado = listaGrados.get(gradoSeleccionado);
        
        int idGrado = grado.getIdGrado();
        try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            PreparedStatement pstm = conexion.prepareCall("call sp_matricular_estudiante(?,?,?)");
            
            pstm.setString(1, documento);
            pstm.setString(2, nombre);
            pstm.setInt(3, idGrado);
            pstm.execute();
            limpiar();
            mostrarMatriculados();
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error de la base de datos " + e);
        }
        
    }//GEN-LAST:event_btnMatricularActionPerformed
    private void limpiar(){
        txtDocumento.setText("");
        txtNombreCompleto.setText("");
    }
    private void mostrarMatriculados(){
        try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            DefaultTableModel modelo = new DefaultTableModel();
            
            PreparedStatement pstm = conexion.prepareCall("call sp_matriculados()");
            ResultSet rs = pstm.executeQuery();
            
            ResultSetMetaData rsmt = rs.getMetaData();
            
            for(int i =1; i<= rsmt.getColumnCount(); i++){
                modelo.addColumn(rsmt.getColumnLabel(i));
            }
            while (rs.next()) {                
                modelo.addRow(new Object[]{rs.getString("Documento"),rs.getString("Estudiante"),rs.getString("Grado")});
            }
            
            tableMatriculados.setModel(modelo); 
            
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error de la base de datos " + e);
        }
    }
    
    private void llenarcombo(){
        try (Connection conexion = DriverManager.getConnection(con.getUrl(), con.getUsername(), con.getPassword())) {
            
            PreparedStatement pstm = conexion.prepareCall("call sp_combo_grados()");
            ResultSet rs = pstm.executeQuery();
            cbmGrado.removeAllItems();
            cbmGrado.addItem("Seleccione...");
            while (rs.next()) {     
                int id = rs.getInt("idGrado");
                String nombre = rs.getString("nombreGrado");
                Grado grado = new Grado(id,nombre);
                cbmGrado.addItem(grado.getNombre());
                listaGrados.add(grado);
            }
        }catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error de la base de datos" + e);
        }
    }

